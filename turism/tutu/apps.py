from django.apps import AppConfig


class TutuConfig(AppConfig):
    """
    Конфигурация Django приложения 'tutu'.

    Этот файл определяет настройки и метаданные приложения.
    Django автоматически находит и загружает этот класс при запуске.
    """

    # Тип поля для автоматического создания первичных ключей
    # BigAutoField создает 64-битные целые числа (от 1 до 9223372036854775807)
    # Это современная замена старому AutoField (32-битные числа)
    default_auto_field = 'django.db.models.BigAutoField'

    # Имя Python пути к приложению
    # Должно соответствовать имени папки приложения
    name = 'tutu'

    # Человеко-читаемое название приложения
    # Отображается в админке Django вместо технического имени 'tutu'
    verbose_name = 'Туристическое агентство Tutu'